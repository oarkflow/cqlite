package btree

import (
	"bytes"
	"encoding/binary"
	"sync"
)

// A wider in-memory node reduces split and slice-copy churn on append-heavy
// table workloads while binary search keeps lookups logarithmic in the node.
const defaultOrder = 64

type Tree struct {
	mu       sync.RWMutex
	order    int
	root     *node
	intArena []byte
}

type node struct {
	leaf     bool
	keys     [][]byte
	values   [][]byte
	children []*node
	next     *node
}

type splitResult struct {
	key   []byte
	right *node
}

func New() *Tree {
	return NewWithOrder(defaultOrder)
}

func NewWithOrder(order int) *Tree {
	if order < 4 {
		order = 4
	}
	return &Tree{order: order, root: newLeaf(order)}
}

func newLeaf(order int) *node {
	return &node{leaf: true, keys: make([][]byte, 0, order+1), values: make([][]byte, 0, order+1)}
}

func (t *Tree) installRootSplit(res *splitResult) {
	keys := make([][]byte, 1, t.order+1)
	keys[0] = res.key
	children := make([]*node, 2, t.order+2)
	children[0] = t.root
	children[1] = res.right
	t.root = &node{keys: keys, children: children}
}

func (t *Tree) Put(key, value []byte) {
	t.mu.Lock()
	defer t.mu.Unlock()
	if res := t.insert(t.root, clone(key), clone(value)); res != nil {
		t.installRootSplit(res)
	}
}

func (t *Tree) PutOwned(key, value []byte) {
	t.mu.Lock()
	defer t.mu.Unlock()
	if res := t.insert(t.root, key, value); res != nil {
		t.installRootSplit(res)
	}
}

// PutInt64 inserts an ordered signed integer key and integer value without
// allocating a separate byte slice for every entry. The tree retains the
// encoded bytes from its own arena until the tree is collected.
func (t *Tree) PutInt64(key int64, value int) {
	t.mu.Lock()
	defer t.mu.Unlock()
	if len(t.intArena) < 16 {
		t.intArena = make([]byte, 4096)
	}
	entry := t.intArena[:16:16]
	t.intArena = t.intArena[16:]
	binary.BigEndian.PutUint64(entry[:8], uint64(key)^(uint64(1)<<63))
	binary.LittleEndian.PutUint64(entry[8:], uint64(value))
	if res := t.insert(t.root, entry[:8], entry[8:]); res != nil {
		t.installRootSplit(res)
	}
}

// PutManyOwnedFunc inserts entries generated by next. The tree holds its
// write lock once for the whole batch and takes ownership of returned slices.
func (t *Tree) PutManyOwnedFunc(count int, next func(int) (key, value []byte)) {
	t.mu.Lock()
	defer t.mu.Unlock()
	for i := 0; i < count; i++ {
		key, value := next(i)
		if res := t.insert(t.root, key, value); res != nil {
			t.installRootSplit(res)
		}
	}
}

func (t *Tree) Get(key []byte) ([]byte, bool) {
	t.mu.RLock()
	defer t.mu.RUnlock()
	leaf := findLeaf(t.root, key)
	pos, found := searchKeys(leaf.keys, key)
	if !found {
		return nil, false
	}
	return clone(leaf.values[pos]), true
}

func (t *Tree) View(key []byte, fn func([]byte)) bool {
	t.mu.RLock()
	defer t.mu.RUnlock()
	leaf := findLeaf(t.root, key)
	pos, found := searchKeys(leaf.keys, key)
	if !found {
		return false
	}
	fn(leaf.values[pos])
	return true
}

func (t *Tree) Delete(key []byte) bool {
	t.mu.Lock()
	defer t.mu.Unlock()
	entries := t.entriesLocked()
	found := false
	t.root = newLeaf(t.order)
	for _, entry := range entries {
		if bytes.Equal(entry.key, key) {
			found = true
			continue
		}
		if res := t.insert(t.root, entry.key, entry.value); res != nil {
			t.installRootSplit(res)
		}
	}
	return found
}

func (t *Tree) Scan(start, end []byte, fn func(key, value []byte) bool) {
	t.scan(start, end, func(key, value []byte) bool {
		return fn(clone(key), clone(value))
	})
}

func (t *Tree) ViewScan(start, end []byte, fn func(key, value []byte) bool) {
	t.scan(start, end, fn)
}

func (t *Tree) scan(start, end []byte, fn func(key, value []byte) bool) {
	t.mu.RLock()
	defer t.mu.RUnlock()
	leaf := t.leftmostLeaf()
	if len(start) > 0 {
		leaf = findLeaf(t.root, start)
	}
	for leaf != nil {
		for i, key := range leaf.keys {
			if len(start) > 0 && bytes.Compare(key, start) < 0 {
				continue
			}
			if len(end) > 0 && bytes.Compare(key, end) >= 0 {
				return
			}
			if !fn(key, leaf.values[i]) {
				return
			}
		}
		leaf = leaf.next
	}
}

func (t *Tree) insert(n *node, key, value []byte) *splitResult {
	if n.leaf {
		pos, found := searchKeys(n.keys, key)
		if found {
			n.values[pos] = value
			return nil
		}
		if pos == len(n.keys) {
			// Monotonic inserts are common for rowids. Appending avoids copying
			// the existing leaf on every insert while preserving the general
			// insertion path for out-of-order keys.
			n.keys = append(n.keys, key)
			n.values = append(n.values, value)
		} else {
			n.keys = insertBytes(n.keys, pos, key)
			n.values = insertBytes(n.values, pos, value)
		}
		if len(n.keys) <= t.order {
			return nil
		}
		return splitLeaf(n, t.order)
	}
	pos := childPos(n.keys, key)
	res := t.insert(n.children[pos], key, value)
	if res == nil {
		return nil
	}
	if pos == len(n.children)-1 {
		n.keys = append(n.keys, res.key)
		n.children = append(n.children, res.right)
	} else {
		n.keys = insertBytes(n.keys, pos, res.key)
		n.children = insertChild(n.children, pos+1, res.right)
	}
	if len(n.keys) <= t.order {
		return nil
	}
	return splitInternal(n, t.order)
}

func splitLeaf(left *node, order int) *splitResult {
	mid := len(left.keys) / 2
	keys := make([][]byte, len(left.keys)-mid, order+1)
	copy(keys, left.keys[mid:])
	values := make([][]byte, len(left.values)-mid, order+1)
	copy(values, left.values[mid:])
	right := &node{
		leaf:   true,
		keys:   keys,
		values: values,
		next:   left.next,
	}
	left.keys = left.keys[:mid]
	left.values = left.values[:mid]
	left.next = right
	return &splitResult{key: right.keys[0], right: right}
}

func splitInternal(left *node, order int) *splitResult {
	mid := len(left.keys) / 2
	promoted := left.keys[mid]
	keys := make([][]byte, len(left.keys)-mid-1, order+1)
	copy(keys, left.keys[mid+1:])
	children := make([]*node, len(left.children)-mid-1, order+2)
	copy(children, left.children[mid+1:])
	right := &node{
		keys:     keys,
		children: children,
	}
	left.keys = left.keys[:mid]
	left.children = left.children[:mid+1]
	return &splitResult{key: promoted, right: right}
}

func findLeaf(n *node, key []byte) *node {
	for !n.leaf {
		n = n.children[childPos(n.keys, key)]
	}
	return n
}

func (t *Tree) leftmostLeaf() *node {
	n := t.root
	for n != nil && !n.leaf {
		n = n.children[0]
	}
	return n
}

type entry struct {
	key   []byte
	value []byte
}

func (t *Tree) entriesLocked() []entry {
	var out []entry
	for leaf := t.leftmostLeaf(); leaf != nil; leaf = leaf.next {
		for i := range leaf.keys {
			out = append(out, entry{key: clone(leaf.keys[i]), value: clone(leaf.values[i])})
		}
	}
	return out
}

func searchKeys(keys [][]byte, key []byte) (int, bool) {
	n := len(keys)
	if n <= 16 {
		for i, k := range keys {
			cmp := bytes.Compare(k, key)
			if cmp == 0 {
				return i, true
			}
			if cmp > 0 {
				return i, false
			}
		}
		return n, false
	}
	lo, hi := 0, n
	for lo < hi {
		mid := lo + (hi-lo)/2
		cmp := bytes.Compare(keys[mid], key)
		if cmp < 0 {
			lo = mid + 1
		} else {
			hi = mid
		}
	}
	return lo, lo < len(keys) && bytes.Equal(keys[lo], key)
}

func childPos(keys [][]byte, key []byte) int {
	pos, found := searchKeys(keys, key)
	if found {
		return pos + 1
	}
	return pos
}

func insertBytes(in [][]byte, pos int, value []byte) [][]byte {
	in = append(in, nil)
	copy(in[pos+1:], in[pos:])
	in[pos] = value
	return in
}

func insertChild(in []*node, pos int, value *node) []*node {
	in = append(in, nil)
	copy(in[pos+1:], in[pos:])
	in[pos] = value
	return in
}

func clone(in []byte) []byte {
	if in == nil {
		return nil
	}
	l := len(in)
	if l == 0 {
		return []byte{}
	}
	out := make([]byte, l)
	copy(out, in)
	return out
}
